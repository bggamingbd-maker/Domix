/**
 * export-abis — reads Foundry artifacts and writes typed ABI constants to
 * src/contracts/abis.ts. Run after `forge build`:  bun run abis
 */
import fs from 'node:fs'
import path from 'node:path'

const NAMES = ['Domix'] as const
const root = path.resolve(import.meta.dir, '..')
const outDir = path.join(root, 'src', 'contracts')
fs.mkdirSync(outDir, { recursive: true })

let body = '// GENERATED by server/export-abis.ts from Foundry artifacts. Do not edit.\n\n'
for (const name of NAMES) {
  const file = path.join(root, 'contracts', 'out', `${name}.sol`, `${name}.json`)
  if (!fs.existsSync(file)) throw new Error(`Missing artifact ${file}. Run forge build first.`)
  const artifact = JSON.parse(fs.readFileSync(file, 'utf8')) as { abi: unknown[] }
  const abi = artifact.abi.filter((item) => (item as { type: string }).type !== 'constructor')
  const constructorItem = artifact.abi.find((item) => (item as { type: string }).type === 'constructor')
  const key = name.charAt(0).toLowerCase() + name.slice(1)
  body += `export const ${key}Abi = ${JSON.stringify(abi, null, 2)} as const\n\n`
  if (constructorItem) {
    body += `export const ${key}Constructor = ${JSON.stringify(constructorItem)} as const\n\n`
  }
}
fs.writeFileSync(path.join(outDir, 'abis.ts'), body)
console.log(`Wrote ${path.join(outDir, 'abis.ts')}`)
